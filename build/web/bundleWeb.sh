#!/usr/bin/env bash
# shellcheck disable=SC2059

set -o errexit
set -o nounset
set -o pipefail

# Change to the root directory of the repository
cd "$(git rev-parse --show-toplevel)"

cd web

echo "Installing npm modules for the aoitube web..."
if [ -f package-lock.json ]; then
    echo "Using npm ci (lockfile found)..."
    npm --silent ci
else
    echo "Using npm install (no lockfile found)..."
    npm --silent install
fi

echo "Building aoitube web (Vite)..."
rm -rf out

build_log_file="$(mktemp -t aoitube-web-build.XXXXXX.log)"
trap 'rm -f "$build_log_file"' EXIT

set +o errexit
node_modules/.bin/vite build 2>&1 | tee "$build_log_file"
vite_build_status=${PIPESTATUS[0]}
set -o errexit

if [ "$vite_build_status" -ne 0 ]; then
    echo "Vite build failed (exit code: $vite_build_status). Full log:"
    cat "$build_log_file"
    exit "$vite_build_status"
fi

if [ ! -d out ]; then
    echo "Expected 'out' directory was not generated by the build."
    exit 1
fi

# Two MPA entry shells must be present: the viewer index and the admin index.
# The Go server (controllers/web.go) serves admin/index.html for /admin/* and
# index.html (with server-side template injection) for everything else.
if [ ! -f out/index.html ] || [ ! -f out/admin/index.html ]; then
    echo "Expected out/index.html and out/admin/index.html were not generated."
    exit 1
fi

echo "Copying web project to dist directory..."

# Remove the old one
rm -rf ../static/web

# Copy over the new one
mv ./out ../static/web

echo "Done."
