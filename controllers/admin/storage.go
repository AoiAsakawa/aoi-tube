package admin

import (
	"encoding/json"
	"net/http"
	"os"
	"path/filepath"

	"github.com/aoiasakawa/aoitube/controllers"
	"github.com/aoiasakawa/aoitube/core"
	"github.com/aoiasakawa/aoitube/core/recording"
	"github.com/aoiasakawa/aoitube/core/storageproviders"
)

// storagePrefixUsage is the object count and byte total under one S3 prefix.
type storagePrefixUsage struct {
	Prefix  string `json:"prefix"`
	Objects int64  `json:"objects"`
	Bytes   int64  `json:"bytes"`
}

// GetStorageUsage reports S3/R2 bucket usage grouped by the prefixes this
// server writes: live HLS distribution segments, offloaded VOD archives and
// database backups. "other" is anything else sharing the bucket.
func GetStorageUsage(w http.ResponseWriter, r *http.Request) {
	s3, err := storageproviders.NewArchiveS3()
	if err != nil {
		controllers.WriteSimpleResponse(w, false, "S3 storage is not configured")
		return
	}

	prefixes := []string{"hls/", "archives/", "backups/"}
	out := make([]storagePrefixUsage, 0, len(prefixes)+1)
	var known storagePrefixUsage
	for _, p := range prefixes {
		objects, bytes, err := s3.PrefixUsage(p)
		if err != nil {
			controllers.WriteSimpleResponse(w, false, "failed to inspect bucket: "+err.Error())
			return
		}
		out = append(out, storagePrefixUsage{Prefix: p, Objects: objects, Bytes: bytes})
		known.Objects += objects
		known.Bytes += bytes
	}

	totalObjects, totalBytes, err := s3.PrefixUsage("")
	if err != nil {
		controllers.WriteSimpleResponse(w, false, "failed to inspect bucket: "+err.Error())
		return
	}
	out = append(out, storagePrefixUsage{
		Prefix:  "other",
		Objects: totalObjects - known.Objects,
		Bytes:   totalBytes - known.Bytes,
	})

	// Incomplete multipart uploads are billed but invisible to ListObjects,
	// so surface their count alongside the listable usage.
	multipart, err := s3.CountIncompleteMultipartUploads()
	if err != nil {
		multipart = -1
	}

	controllers.WriteResponse(w, map[string]interface{}{
		"prefixes":                   out,
		"totalObjects":               totalObjects,
		"totalBytes":                 totalBytes,
		"incompleteMultipartUploads": multipart,
	})
}

// CleanupStorage deletes dead objects from the shared bucket. Targets:
//
//	"livehls"         — every live distribution segment under hls/. Only
//	                    allowed while offline: these exist purely to serve the
//	                    in-progress broadcast and are fully regenerated by the
//	                    next stream, but were never cleaned up historically.
//	"orphan-archives" — archives/<id>/ prefixes whose session no longer exists
//	                    locally (leftovers of interrupted offloads/deletes).
func CleanupStorage(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodPost {
		controllers.WriteSimpleResponse(w, false, r.Method+" not supported")
		return
	}

	var req struct {
		Target string `json:"target"`
	}
	if err := json.NewDecoder(r.Body).Decode(&req); err != nil {
		controllers.WriteSimpleResponse(w, false, "invalid request body")
		return
	}

	s3, err := storageproviders.NewArchiveS3()
	if err != nil {
		controllers.WriteSimpleResponse(w, false, "S3 storage is not configured")
		return
	}

	switch req.Target {
	case "livehls":
		if core.GetStatus().Online {
			controllers.WriteSimpleResponse(w, false, "cannot clean live segments while a stream is online")
			return
		}
		objects, bytes, err := s3.PrefixUsage("hls/")
		if err != nil {
			controllers.WriteSimpleResponse(w, false, "failed to inspect bucket: "+err.Error())
			return
		}
		if err := s3.DeleteRawPrefix("hls/"); err != nil {
			controllers.WriteSimpleResponse(w, false, "cleanup failed: "+err.Error())
			return
		}
		controllers.WriteResponse(w, map[string]interface{}{
			"deletedObjects": objects,
			"freedBytes":     bytes,
		})

	case "orphan-archives":
		sessionIDs, err := s3.ListArchiveSessionPrefixes()
		if err != nil {
			controllers.WriteSimpleResponse(w, false, "failed to list archive prefixes: "+err.Error())
			return
		}
		var deletedObjects, freedBytes int64
		deletedPrefixes := []string{}
		for _, id := range sessionIDs {
			if _, err := os.Stat(filepath.Join(recording.ArchiveBasePath, id)); err == nil {
				continue // session still exists locally — not an orphan
			}
			objects, bytes, err := s3.PrefixUsage("archives/" + id + "/")
			if err != nil {
				continue
			}
			if err := s3.DeletePrefix(id); err != nil {
				continue
			}
			deletedObjects += objects
			freedBytes += bytes
			deletedPrefixes = append(deletedPrefixes, id)
		}
		controllers.WriteResponse(w, map[string]interface{}{
			"deletedPrefixes": deletedPrefixes,
			"deletedObjects":  deletedObjects,
			"freedBytes":      freedBytes,
		})

	case "multipart":
		aborted, err := s3.AbortAllMultipartUploads()
		if err != nil {
			controllers.WriteSimpleResponse(w, false, "abort failed: "+err.Error())
			return
		}
		controllers.WriteResponse(w, map[string]interface{}{
			"abortedUploads": aborted,
		})

	default:
		controllers.WriteSimpleResponse(w, false, "unknown cleanup target")
	}
}
