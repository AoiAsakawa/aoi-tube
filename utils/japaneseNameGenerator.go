// GenerateJapaneseName will generate and return a random Japanese-style name.
func GenerateJapaneseName() string {
	r := rand.New(rand.NewSource(time.Now().UnixNano()))

	adjIndex := r.Intn(len(japaneseAdjectives))
	nounIndex := r.Intn(len(japaneseNouns))

	return fmt.Sprintf("%s%s", japaneseAdjectives[adjIndex], japaneseNouns[nounIndex])
}
